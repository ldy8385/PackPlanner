// 빠른 조회용 Map
export const manufacturerMap = new Map<string, Manufacturer>(
  manufacturers.map(m => [m.key, m]),
);

export const getManufacturerName = (key: string | undefined, lang: string): string => {
  if (!key) return '';
  const m = manufacturerMap.get(key);
  if (!m) return key;
  return lang === 'en' ? m.en : m.ko;
};
